export function translate(lang, key, params) {
  const entry = dict[lang] || dict.en;
  // English is the safety-net fallback for keys missing in the active
  // language (rather than Italian), since English is the most complete
  // and universally understood reference translation.
  let str = entry[key] || dict.en[key] || key;
  if (params) Object.entries(params).forEach(([k, v]) => { str = str.replace(`{${k}}`, v); });
  return str;
}

